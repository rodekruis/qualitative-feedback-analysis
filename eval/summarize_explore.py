"""Hand-inspection loop for ``POST /v1/summarize-bulk`` on Ukrainian feedback.

Not a scoring run. It fetches a batch of records, translates them to English so
a non-Ukrainian reader can judge the result, gets one aggregate summary, runs a
panel of LLM judges over it, and prints everything side by side.

**What costs money, and what does not.** Translations and summaries are cached
on disk, keyed by the records they were produced from, so re-running the same
batch re-uses both and costs nothing for them. Judges are deliberately *not*
cached: they are the thing under development here, and a cached verdict from an
older prompt would be worse than no verdict. A repeat run costs
``JUDGE_REPEATS`` calls: one call scores every dimension and runs the
grounding audit together.

**Comparing summarisation approaches.** :func:`evaluate` takes a named
``(title, summary)`` candidate, so a second approach is one more call to it
with the same records and the same judges. The baseline candidate below comes
from the deployed endpoint, which uses the prompt in
:mod:`qfa.services.summarize`.

The records are sent to the LLM as they come out of the dataset: the Langfuse
dataset below is already anonymised at source. Any *other* source of feedback
text must be redacted before the first LLM call, since the direct calls here
bypass the redaction the endpoint does internally.

Run with ``uv run python eval/summarize_explore.py``.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import os
import statistics
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import dotenv
import httpx
from langfuse import get_client
from litellm import acompletion
from pydantic import BaseModel

REPO_ROOT = Path(__file__).resolve().parents[1]
dotenv.load_dotenv(REPO_ROOT / ".env")

DATASET_NAME = "assign-codes/ukrain"
DEFAULT_BASE_URL = "https://qfa-dev-backend.azurewebsites.net"
REQUEST_TIMEOUT_SECONDS = 300.0
N_RECORDS = 10
OUTPUT_LANGUAGE = "English"
OUT_DIR = REPO_ROOT / "eval" / "runs"
TRANSLATION_CACHE = REPO_ROOT / "eval" / "translation-cache.json"
SUMMARY_CACHE = REPO_ROOT / "eval" / "summary-cache.json"

# How many times each panel is asked the same question. LLM judges are noisy:
# one call gives a number with unknown error bars, three give a spread you can
# read. Raise it while calibrating a panel's prompt, drop back to 1 once its
# verdicts stop moving. Note this measures *sampling noise only* — repeating one
# model cannot reveal that model's bias, which is what the per-panel models in
# the TODO below are for.
JUDGE_REPEATS = 1

_TRANSLATE_PROMPT = (
    "Translate the text to English. Translate only — do not summarize,"
    " explain, or add anything. Keep the register and any vagueness of the"
    " original. Return the translation and nothing else."
)


@dataclass(frozen=True)
class Dimension:
    """One thing a judge scores, phrased as the question a reviewer would ask."""

    key: str
    question: str
    anchors: str
    """What 1.0 and 0.0 mean. Without these, scores drift between runs."""


@dataclass(frozen=True)
class Panel:
    """A group of dimensions scored together by one judge in one call.

    The grouping is by *what the judge has to look at*: the evidence panel
    compares summary against records, the usability panel mostly reads the
    summary alone. Dimensions that need the same reading are cheaper and more
    consistent judged together.

    ``model`` is the seam for the eventual split (see the TODO below). While it
    is ``None`` every panel runs on the default connection, which is the
    cost-saving arrangement for now.
    """

    name: str
    dimensions: tuple[Dimension, ...]
    model: str | None = None


# TODO(judges): split the panels into separate calls, each on its own model,
# ideally from a different vendor. Three separate reasons, all real:
#   1. Criteria bleed. One call scoring six dimensions forms a single overall
#      impression and spreads it across all six: a judge that decides the
#      summary is unfaithful marks its clarity down too, though the two are
#      unrelated. Splitting the call is what makes the scores independent, and
#      independence is exactly what is needed to compare two summarisation
#      approaches dimension by dimension. Acceptable while the dimensions
#      themselves are still being worked out; not acceptable once the numbers
#      are used to choose between approaches.
#   2. Self-grading. The summary is generated by LLM_MODEL and, right now, the
#      judge runs on that same model. Models score their own output generously.
#      The codebase already treats this as a real problem — see the JUDGE_LLM_*
#      settings block in qfa.settings, whose stated purpose is "so the generator
#      does not grade its own homework".
#   3. Vendor-correlated blind spots. Two models from one vendor share training
#      data and RLHF conventions, so they tend to miss the same things. Panels on
#      models from different enterprises disagree in useful ways; where they
#      agree, the verdict is worth more.
# Note that (1) is fixed by splitting the calls alone, whatever model each one
# runs on; (2) and (3) additionally need different models behind them.
# Implementation sketch: read a JSON map of panel name -> model from a
# JUDGE_MODELS env var, set Panel.model from it, and have _llm_kwargs take an
# optional model override. Each vendor needs its own api_base/api_key, so the
# override has to carry a whole connection, not just a model string.
#
# TODO(judges): once panels run on different models, report inter-judge
# agreement per dimension. Two models scoring faithfulness 0.9 and 0.3 is the
# most informative thing an eval can tell you, and averaging it away to 0.6
# throws it out.

_FAITHFULNESS = Dimension(
    key="faithfulness",
    question="Did the summary say anything that isn't supported by the feedback?",
    anchors=(
        "1.0 = every claim traceable to at least one record, and any statement"
        " about how widespread an issue is matches the records."
        " 0.5 = broadly right, but at least one claim is overstated or"
        " unsupported. 0.0 = major claims appear nowhere in the records."
        " Put every unsupported or overstated claim in evidence."
    ),
)

_COVERAGE = Dimension(
    key="coverage",
    question="Did it capture the important themes in the feedback?",
    anchors=(
        "1.0 = every theme raised by more than one record is represented."
        " 0.5 = the main themes are there but notable ones are missing."
        " 0.0 = most of what the records raise is absent."
        " Put the missing themes in evidence."
    ),
)

_REPRESENTATIVENESS = Dimension(
    key="representativeness",
    question=(
        "Is what gets emphasized in the summary reasonably representative of"
        " the feedback?"
    ),
    anchors=(
        "Judge proportion, not presence: a theme in eight records should carry"
        " more weight than one in a single record."
        " 1.0 = emphasis and ordering track how often each theme appears."
        " 0.5 = a minor point is given prominence, or a common one is buried."
        " 0.0 = emphasis unrelated to how often themes appear."
        " Put the over- and under-weighted themes in evidence."
    ),
)

_NEUTRALITY = Dimension(
    key="neutrality",
    question="Did the wording change the meaning, certainty or tone?",
    anchors=(
        "Look for hedged complaints turned into firm findings, or the reverse;"
        " for emotive wording the records do not use; for blame assigned that"
        " the records do not assign."
        " 1.0 = wording preserves the meaning, certainty and tone of the"
        " records. 0.5 = some shift in strength or tone. 0.0 = the summary"
        " reads as a different claim than the records make."
        ' Put each shifted phrase in evidence, as "records say X -> summary'
        ' says Y".'
    ),
)

_CLARITY = Dimension(
    key="clarity",
    question="Can a Red Cross staff member quickly understand the main findings?",
    anchors=(
        "1.0 = the main findings land on one read, with no jargon or tangled"
        " sentences. 0.5 = understandable but needs re-reading."
        " 0.0 = confusing or badly organised."
        " Put the hardest passages in evidence."
    ),
)

_ACTIONABILITY = Dimension(
    key="actionability",
    question="Does it make clear what deserves attention or follow-up?",
    anchors=(
        "1.0 = names concrete, specific problems a team could act on."
        " 0.5 = recognisable but vague, needing the records before acting."
        " 0.0 = generic phrasing that would fit any feedback batch."
        " Put the vaguest bullets in evidence."
    ),
)

PANELS: tuple[Panel, ...] = (
    # Unsupported claims are this panel's job too: they come back in the
    # faithfulness verdict's `evidence`, and per-bullet in grounding_report.
    Panel("evidence", (_FAITHFULNESS,)),
    Panel("representation", (_COVERAGE, _REPRESENTATIVENESS)),
    Panel("usability", (_NEUTRALITY, _CLARITY, _ACTIONABILITY)),
)

_PANEL_OF: dict[str, str] = {
    dimension.key: panel.name for panel in PANELS for dimension in panel.dimensions
}
"""Which panel each dimension belongs to.

Reported alongside every score so the grouping stays visible in the output
even while a single call produces them all.
"""


class DimensionScore(BaseModel):
    """One dimension's verdict: a 0-1 score, why, and what it looked at."""

    dimension: str
    score: float
    reason: str
    evidence: list[str]


class BulletGrounding(BaseModel):
    """One summary bullet and the records a judge could trace it back to."""

    bullet: str
    supporting_record_ids: list[str]
    supported: bool
    reason: str


class JudgeReport(BaseModel):
    """Everything one judge call returns: per-dimension scores and per-bullet grounding."""

    scores: list[DimensionScore]
    bullets: list[BulletGrounding]
    missed_themes: list[str]


_JUDGE_PREAMBLE = """
You are evaluating an aggregate summary of community feedback records
collected by a humanitarian organisation during an operation in Ukraine.

Feedback records (id: text):
---
{records}
---

Summary:
---
{summary}
---
"""

_GROUNDING_TASK = """
Then, for every bullet in the summary:
- list the ids of the records that support it (empty list if none),
- set supported=false if no record supports it, or if it overstates how many
  records raise the issue,
- give a one-sentence reason.

Finally list any theme raised in the records that the summary does not mention
at all, as short English phrases in missed_themes.
"""


def resolve_api_key() -> str:
    """The API key to call the QFA service with.

    ``QFA_DEV_API_KEY`` first — the convention ``assign_codes_eval.py`` and the
    **evaluate** CI workflow use, so this script works unchanged wherever that
    one does. Falling back to ``AUTH_API_KEYS`` means a local run needs nothing
    beyond the keys the local server is already configured with.

    The fallback parses that JSON by hand rather than going through
    ``AuthSettings``: :class:`~qfa.domain.models.TenantApiKey` blanks the
    plaintext ``key`` as soon as it has hashed it, so the settings object can
    only ever answer with ``None``. Any entry authenticates — these endpoints
    need no superuser flag.
    """
    if key := os.environ.get("QFA_DEV_API_KEY"):
        return key
    raw = os.environ.get("AUTH_API_KEYS")
    if not raw:
        raise SystemExit(
            "No API key: set QFA_DEV_API_KEY, or AUTH_API_KEYS to the same "
            "JSON the server consumes."
        )
    for entry in json.loads(raw):
        if key := entry.get("key"):
            return str(key)
    raise SystemExit(
        "No usable API key in AUTH_API_KEYS: every entry stores only a "
        "'hashed_key'. Set QFA_DEV_API_KEY instead, or give one entry a "
        "plaintext 'key'."
    )


def _llm_kwargs(model: str | None = None) -> dict[str, Any]:
    """LiteLLM connection kwargs read from the same ``LLM_*`` env vars as the app.

    ``model`` overrides only the model name, so it reaches a different
    deployment on the *same* endpoint. A genuinely different vendor needs its
    own ``api_base`` and ``api_key`` too — see the per-panel model TODO above.
    """
    kwargs: dict[str, Any] = {
        "model": model or os.environ.get("LLM_MODEL", "azure/gpt-5.4"),
        "api_key": os.environ["LLM_API_KEY"],
    }
    if api_base := os.environ.get("LLM_API_BASE"):
        kwargs["api_base"] = api_base
    if api_version := os.environ.get("LLM_API_VERSION"):
        kwargs["api_version"] = api_version
    return kwargs


def _digest(payload: Any) -> str:
    """Short stable hash of any JSON-serialisable payload, for cache keys."""
    blob = json.dumps(payload, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def _read_cache(path: Path) -> dict[str, Any]:
    """The cache at ``path``, or an empty one if it does not exist yet."""
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def _write_cache(path: Path, cache: dict[str, Any]) -> None:
    """Persist ``cache`` to ``path`` as indented JSON."""
    path.write_text(json.dumps(cache, indent=2, ensure_ascii=False), encoding="utf-8")


async def _translate(text: str) -> str:
    """One LLM call returning ``text`` in English."""
    response = await acompletion(
        messages=[
            {"role": "system", "content": _TRANSLATE_PROMPT},
            {"role": "user", "content": text},
        ],
        **_llm_kwargs(),
    )
    return response.choices[0].message.content.strip()


async def translate_to_english(texts: list[str]) -> list[str]:
    """Translate every text, reusing anything already in the on-disk cache.

    The translations exist only so a non-Ukrainian reader can judge the
    summary — they are never fed back into the pipeline — so a stale one is
    harmless and re-paying for them on every iteration is not. Keyed by a hash
    of the source text, so edited records are re-translated.
    """
    cache = _read_cache(TRANSLATION_CACHE)
    keys = [_digest(text) for text in texts]
    missing = {k: t for k, t in zip(keys, texts, strict=True) if k not in cache}
    if missing:
        fresh = await asyncio.gather(*(_translate(t) for t in missing.values()))
        cache.update(zip(missing, fresh, strict=True))
        _write_cache(TRANSLATION_CACHE, cache)
    print(f"translations: {len(missing)} new, {len(texts) - len(missing)} cached")
    return [cache[key] for key in keys]


async def summarize_bulk(records: list[dict[str, str]]) -> dict[str, Any]:
    """The endpoint's aggregate summary for ``records``, from cache when seen before.

    Keyed by the records plus the output language, so the same batch always
    yields the same baseline to judge against. That is the point as much as the
    saved cost: a summary that changes underneath you makes two judge runs
    incomparable. Delete ``summary-cache.json`` to force a fresh generation —
    for instance after editing the prompt in :mod:`qfa.services.summarize`.
    """
    key = _digest({"records": records, "language": OUTPUT_LANGUAGE})
    cache = _read_cache(SUMMARY_CACHE)
    if cached := cache.get(key):
        print(f"summary: reused from cache ({key})")
        return cached

    base_url = os.environ.get("QFA_API_BASE_URL", DEFAULT_BASE_URL)
    body = {"feedback_records": records, "output_language": OUTPUT_LANGUAGE}
    async with httpx.AsyncClient(
        base_url=base_url, timeout=REQUEST_TIMEOUT_SECONDS
    ) as client:
        response = await client.post(
            "/v1/summarize-bulk",
            json=body,
            headers={"Authorization": f"Bearer {resolve_api_key()}"},
        )
    response.raise_for_status()
    result = response.json()

    cache[key] = result
    _write_cache(SUMMARY_CACHE, cache)
    print(f"summary: generated and cached ({key})")
    return result


def _render_records(records: list[dict[str, str]]) -> str:
    """The records as ``id: text`` blocks, the shape the judge prompt expects."""
    return "\n\n".join(f"{r['id']}: {r['content']}" for r in records)


def build_judge_prompt(records: str, summary: str) -> str:
    """The whole judging instruction: every dimension, then the grounding audit.

    Built from :data:`PANELS` even though one call covers them all, so splitting
    the panels later is a change to how these blocks are *distributed*, not a
    rewrite of the wording.
    """
    blocks = "\n\n".join(
        f"Dimension '{d.key}' ({panel.name} judge): {d.question}\nScoring: {d.anchors}"
        for panel in PANELS
        for d in panel.dimensions
    )
    return (
        _JUDGE_PREAMBLE.format(records=records, summary=summary)
        + "\nScore the summary on each dimension below. Every score is a float"
        " between 0 and 1. Return one entry per dimension, using the dimension"
        " key exactly as given.\n\n" + blocks + "\n" + _GROUNDING_TASK
    )


async def judge_summary(
    records: list[dict[str, str]], summary: str, repeats: int = JUDGE_REPEATS
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Judge one summary. Returns ``(per-dimension scores, grounding report)``.

    One LLM call covers every dimension and the grounding audit — the cheapest
    arrangement while the criteria themselves are still being worked out. The
    per-panel split the TODO above describes turns this into one call per panel.

    Asking ``repeats > 1`` re-runs the whole call and reports the mean plus the
    spread per dimension. A dimension whose score swings by 0.25 between
    identical calls is not measuring anything stable, and its anchors need
    tightening before the number is worth reading.
    """
    prompt = build_judge_prompt(_render_records(records), summary)
    reports = await asyncio.gather(*(_ask_judge(prompt) for _ in range(repeats)))

    by_dimension: dict[str, list[DimensionScore]] = {}
    for report in reports:
        for score in report.scores:
            by_dimension.setdefault(score.dimension, []).append(score)

    scores = {
        dimension: {
            "panel": _PANEL_OF.get(dimension, "?"),
            "mean": round(statistics.fmean(s.score for s in group), 3),
            "spread": round(
                max(s.score for s in group) - min(s.score for s in group), 3
            ),
            "scores": [s.score for s in group],
            "reasons": [s.reason for s in group],
            "evidence": sorted({e for s in group for e in s.evidence}),
        }
        for dimension, group in by_dimension.items()
    }
    # The grounding audit is per-bullet prose, so averaging it across repeats
    # would be meaningless: keep the first report's.
    grounding = {
        "bullets": [b.model_dump() for b in reports[0].bullets],
        "missed_themes": reports[0].missed_themes,
    }
    return scores, grounding


async def _ask_judge(prompt: str, model: str | None = None) -> JudgeReport:
    """One judge call returning scores and grounding together."""
    response = await acompletion(
        messages=[{"role": "system", "content": prompt}],
        response_format=JudgeReport,
        **_llm_kwargs(model),
    )
    return JudgeReport.model_validate_json(response.choices[0].message.content)


def code_recall(summary: str, expected_codes: set[str]) -> dict[str, Any]:
    """Fraction of the dataset's ground-truth code names the summary mentions.

    A cheap reference-based signal this dataset gives for free: the coding
    labels attached to each record name the themes a good aggregate summary
    should surface. Substring matching is crude — a summary can name a theme
    in other words — so read it as a floor, not a score.
    """
    lowered = summary.lower()
    hit = {code for code in expected_codes if code.lower() in lowered}
    return {
        "recall": len(hit) / len(expected_codes) if expected_codes else None,
        "matched": sorted(hit),
        "missed": sorted(expected_codes - hit),
    }


def surface_checks(title: str, summary: str) -> dict[str, Any]:
    """Deterministic prompt-compliance checks — no LLM, no cost."""
    bullets = [
        line
        for line in summary.splitlines()
        if line.strip().startswith(("-", "*", "•"))
    ]
    return {
        "bullet_count": len(bullets),
        "title_word_count": len(title.split()),
        "has_code_fence": "```" in summary,
        "ends_with_question": summary.strip().endswith("?"),
        "char_count": len(summary),
    }


async def evaluate(
    name: str,
    records: list[dict[str, str]],
    title: str,
    summary: str,
    expected_codes: set[str],
) -> dict[str, Any]:
    """Every evaluator applied to one named candidate summary.

    ``name`` labels the approach that produced the summary ("endpoint" for the
    deployed prompt). Call this once per approach with the same ``records`` and
    the results are directly comparable.
    """
    judges, grounding = await judge_summary(records, summary)
    return {
        "candidate": name,
        "surface": surface_checks(title, summary),
        "code_recall": code_recall(summary, expected_codes),
        "judges": judges,
        "grounding": grounding,
    }


def _expected_codes(item: Any) -> set[str]:
    """Every ground-truth code name on one dataset item, across all levels."""
    expected = item.expected_output or {}
    return {
        str(name).strip()
        for names in expected.values()
        for name in (names if isinstance(names, list) else [names])
        if str(name).strip()
    }


def _print_scores(judges: dict[str, Any]) -> None:
    """One line per dimension: panel, mean, spread, and the first reason given."""
    for dimension, result in judges.items():
        flag = "  <- unstable" if result["spread"] >= 0.25 else ""
        print(
            f"{result['panel']:<15}{dimension:<20}{result['mean']:.2f}"
            f"  (spread {result['spread']:.2f}){flag}"
        )
        print(f"{'':<35}{result['reasons'][0]}")


async def main() -> None:
    """Fetch, translate, summarize, judge, print, and save one run."""
    dataset = get_client().get_dataset(DATASET_NAME)
    items = dataset.items[:N_RECORDS]
    print(f"{DATASET_NAME}: {len(dataset.items)} items, using the first {len(items)}\n")

    ids = [str(item.id) for item in items]
    records = [{"id": str(item.id), "content": item.input["content"]} for item in items]

    # Translations are for the reader only: the summary is produced from the
    # Ukrainian originals, the way the service runs in production.
    translations = await translate_to_english([r["content"] for r in records])
    english = [{"id": i, "content": t} for i, t in zip(ids, translations, strict=True)]

    result = await summarize_bulk(records)

    print("\n" + "=" * 72)
    print(f"TITLE: {result['title']}\n")
    print(result["summary"])
    print(f"\nendpoint quality_score: {result['quality_score']}")

    print("\n" + "=" * 72 + "\nSOURCE RECORDS (English)\n")
    for record in english:
        print(f"--- {record['id']}\n{record['content']}\n")

    expected = set().union(*(_expected_codes(item) for item in items))
    evaluation = await evaluate(
        "endpoint", english, result["title"], result["summary"], expected
    )

    print("=" * 72 + f"\nJUDGES (one call, {JUDGE_REPEATS} repeat(s))\n")
    _print_scores(evaluation["judges"])
    print("\n" + "=" * 72)
    print(
        json.dumps(
            {k: v for k, v in evaluation.items() if k != "judges"},
            indent=2,
            ensure_ascii=False,
        )
    )

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    path = OUT_DIR / f"summarize-{stamp}.json"
    path.write_text(
        json.dumps(
            {
                "dataset": DATASET_NAME,
                "n_records": len(records),
                "records_original": records,
                "records_english": english,
                "response": result,
                "evaluations": [evaluation],
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    print(f"\nsaved {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    asyncio.run(main())
